/* Actual Chromium walkthrough. Service integration proof is deliberately absent. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.CRASHCART_PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'evidence/runs/browser');
fs.mkdirSync(out, {recursive:true});
const token = fs.readFileSync(path.join(root,'.env'),'utf8').split('\n').find(l=>l.startsWith('CRASHCART_OPERATOR_TOKEN=')).split('=').slice(1).join('=');
const fixture = JSON.parse(fs.readFileSync(path.join(root,'var/browser-check/fixture.json')));
const base = process.env.CRASHCART_BROWSER_URL || 'http://127.0.0.1:8766';
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CRASHCART_CHROMIUM});
 const context=await browser.newContext({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
 const page=await context.newPage();const errors=[];const assertions=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&!/401|503|404/.test(m.text()))errors.push(m.text());});
 const check=(name,value)=>{assert(value,name);assertions.push({name,passed:true});};
 try{
  await page.goto(base);await page.getByText('Open your investigation desk.').waitFor();
  check('Page identity and meaningful first screen',await page.title()==='CrashCart — payment meets promise');
  await page.keyboard.press('Tab');check('Keyboard skip link receives focus',await page.locator('.skip').evaluate(e=>e===document.activeElement));
  await page.getByLabel('Operator token').fill(token);await page.getByRole('button',{name:'Open workspace'}).click();
  await page.getByText('Start with a broken promise.').waitFor();
  await page.getByLabel('Promise or customer complaint').fill('Browser walkthrough: paid customer reports missing workshop ticket.');
  await page.getByRole('button',{name:'Create investigation'}).click();
  await page.locator('#run-title').filter({hasText:'Browser walkthrough'}).waitFor();
  const runId=await page.locator('#run-id').textContent();
  check('New UI input creates uniquely identified backend run',/^run_/.test(runId));
  check('Unpaid purchase has zero actual merchant tickets',(await page.locator('#merchant-title').textContent())==='0 tickets');
  check('Unpaid run cannot offer an unsupported regression download',await page.locator('#regression').isHidden());
  await page.locator('#busy').waitFor({state:'hidden'});
  await page.getByRole('button',{name:'Start sandbox checkout'}).click();
  await page.locator('#message').filter({hasText:'CRASHCART_ALLOW_SANDBOX=1'}).waitFor();
  check('Unavailable sandbox is explicit; no fake payment',await page.locator('#provider-title').textContent()==='Not independently read');
  await page.reload();await page.locator('#run-id').filter({hasText:runId}).waitFor();
  check('Refresh reconnects to persisted selected run',await page.locator('#run-title').textContent()==='Browser walkthrough: paid customer reports missing workshop ticket.');
  await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
  const exportResponse=await page.request.get(`${base}/api/runs/${runId}/export`);
  const exported=await exportResponse.json();
  check('Inspection export labels non-runnable status',exported.runnable_replay===false&&exported.run.id===runId);
  let releaseSelection, selectionPending;
  const selectionHeld=new Promise(resolve=>releaseSelection=resolve);
  const selectionSeen=new Promise(resolve=>selectionPending=resolve);
  await page.route(`**/api/runs/${fixture.run_id}`,async route=>{selectionPending();await selectionHeld;await route.continue();});
  await page.locator(`[data-run-id="${fixture.run_id}"]`).click();
  await selectionSeen;
  check('Changing selection hides stale panel and disables cancellation',await page.locator('#case').isHidden()&&await page.locator('#cancel-run').isDisabled());
  releaseSelection();
  await page.locator('#run-id').filter({hasText:fixture.run_id}).waitFor();
  await page.locator('#busy').waitFor({state:'hidden'});
  await page.unroute(`**/api/runs/${fixture.run_id}`);
  await page.reload();await page.locator('#run-id').filter({hasText:fixture.run_id}).waitFor();
  check('Refresh retains the newly selected run',new URL(page.url()).searchParams.get('run')===fixture.run_id);
  await page.locator(`[data-run-id="${runId}"]`).click();
  await page.locator('#run-id').filter({hasText:runId}).waitFor();await page.locator('#busy').waitFor({state:'hidden'});
  let releaseStale, stalePending;
  const staleHeld=new Promise(resolve=>releaseStale=resolve);
  const staleSeen=new Promise(resolve=>stalePending=resolve);
  await page.route(`**/api/runs/${runId}`,async route=>{stalePending();await staleHeld;await route.continue();});
  await staleSeen;
  await page.locator(`[data-run-id="${fixture.run_id}"]`).click();
  await page.locator('#run-id').filter({hasText:fixture.run_id}).waitFor();await page.locator('#busy').waitFor({state:'hidden'});
  releaseStale();
  await page.waitForResponse(response=>response.url().endsWith(`/api/runs/${runId}`));
  await page.waitForTimeout(100);
  check('Late detail response cannot replace the newly selected run',(await page.locator('#run-id').textContent())===fixture.run_id);
  await page.unroute(`**/api/runs/${runId}`);
  await page.locator(`[data-run-id="${runId}"]`).click();
  await page.locator('#run-id').filter({hasText:runId}).waitFor();await page.locator('#busy').waitFor({state:'hidden'});
  let releaseInvestigation;
  let signalPending;
  const pending = new Promise(resolve=>signalPending=resolve);
  const held = new Promise(resolve=>releaseInvestigation=resolve);
  await page.route('**/api/runs/*/investigate', async route=>{
    signalPending(); await held;
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({status:'CANCELLED',reason:'LOCAL_TEST deliberately delayed investigation request'})});
  });
  await page.getByRole('button',{name:'Ask investigator',exact:true}).click();
  await pending;
  check('Pending action disables other mutations',await page.locator('#start-button').isDisabled()&&await page.locator('#checkout').isDisabled()&&await page.locator('#reconcile').isDisabled()&&await page.locator('#investigate').isDisabled());
  check('Pending action keeps cancellation available',await page.locator('#cancel-run').isEnabled());
  await page.getByRole('button',{name:'Cancel run',exact:true}).click();
  await page.locator('#run-state').filter({hasText:'cancelled'}).waitFor();
  check('Cancel reaches backend while investigation request remains pending',await page.locator('#busy').isVisible());
  check('Refresh while pending cannot re-enable create',await page.locator('#start-button').isDisabled());
  releaseInvestigation();
  await page.locator('#busy').waitFor({state:'hidden'});
  check('Finishing action restores creation control',await page.locator('#start-button').isEnabled());
  check('Cancellation disables payment actions and preserves evidence',await page.locator('#checkout').isDisabled()&&(await page.locator('.event').count())>0);
  await page.goto(`${base}/?run=${fixture.run_id}`);await page.locator('#ticket-id').filter({hasText:fixture.ticket_id}).waitFor();
  check('Displayed ticket matches isolated actual merchant store',(await page.locator('#provenance').textContent()).includes('LOCAL_TEST'));
  const record=await (await page.request.get(`${base}/api/merchant/${fixture.purchase_id}`)).json();
  check('Read-only merchant adapter matches displayed ticket',record.ticket_count===1&&record.tickets[0].id===fixture.ticket_id);
  const missing=await (await page.request.get(`${base}/api/merchant/no-such-purchase`)).json();
  check('Missing purchase distinct from unpaid',missing.known===false&&missing.ticket_count===null);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(out,'mobile-top.png'),fullPage:false});
  await page.locator('#ticket-card').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(out,'mobile-ticket.png'),fullPage:false});
  check('Mobile layout has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  check('Reduced motion honored',await page.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches&&document.getAnimations().length===0));
  check('No unhandled browser errors',errors.length===0);
  fs.writeFileSync(path.join(out,'walkthrough.json'),JSON.stringify({mode:'LOCAL_TEST',browser:await browser.version(),playwright:require((process.env.CRASHCART_PLAYWRIGHT_MODULE||'playwright')+'/package.json').version,url:base,viewports:[{width:1440,height:1050},{width:390,height:844}],reduced_motion:true,run_id:runId,ticket_fixture:fixture,assertions,errors,expected_http_errors:['401 before login','503 sandbox disabled'],limits:['Synthetic LOCAL_TEST ticket seed; no real payment','No KERNEL or AG Studio execution','Inspection export is not a runnable regression'],executed_at:new Date().toISOString()},null,2));
  console.log(JSON.stringify({passed:assertions.length,errors,mode:'LOCAL_TEST',evidence:'evidence/runs/browser/walkthrough.json'}));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
